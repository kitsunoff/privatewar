---@field _WeaponLevelOf fun(store: PW.ProgressionStore, ply: Player, weaponClass: string): integer
---@field _ViewOf fun(store: PW.ProgressionStore, ply: Player, lookup: PW.LoadoutLookup): PW.ProgressionView

